-- ============================================================================
-- V9__booking_nights.sql
--
-- 全日房支持<b>整晚连住</b>：一张单可以订 N 晚，而不是只能一晚一晚开 N 张。
--
-- 为什么要把晚数也快照下来（而不是从 start/end 反推）：反推需要房型的
-- 全日房模板（full_day_start / full_day_end），而那是<b>房型配置</b>。
-- 改配置不该回溯一张已经开出去的旧单 —— 这和 V7 冻结 covered_minutes 是同一个理由：
-- "这张单当时是怎么卖的"属于订单，不属于房型。
--
-- 允许为 NULL：历史数据没有这一列。BillingService 遇到 NULL 就按当次模板现推，
-- 而连住之前的单必然推成 1 晚，行为与升级前完全一致。
--
-- 起步价覆盖时长（covered_minutes）不用改口径：N 晚的覆盖就是整段预订区间，
-- 中间那些 full_day_end → full_day_start 的白天空档客人房没退，本来就含在房费里。
-- ============================================================================

alter table booking
  add column nights int null comment '下单时快照：全日房连住晚数；钟点房与单晚为 1' after charge_unit_minutes;
