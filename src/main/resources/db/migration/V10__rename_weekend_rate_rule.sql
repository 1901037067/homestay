-- V10__rename_weekend_rate_rule.sql
--
-- 演示规则「周末钟点上浮」名字里写的是"钟点"，但它是 `applies_to = ALL`，
-- 所以周末也在改写<b>全日房的房费</b>。账单上就会出现"一条叫钟点的规则改了房费"，
-- 看的人得先想明白为什么 —— 行为是对的（周末房费上浮是常规做法），名字是错的。
-- 改成「周末上浮」，名字和 `applies_to` 终于说同一件事。
--
-- 为什么不直接改 V5：V5 已经应用到开发库和已部署的库上，改文件会让 Flyway
-- 启动时 checksum 校验失败，整个应用起不来。为了一个演示用的字符串把库弄炸不值得 ——
-- <b>已应用的迁移是不可变的，要改就前滚一条新的。</b>
--
-- 历史账单里仍然写着旧名字：`bill.detail_json` 存的是<b>命中当时</b>的规则名，
-- 那是事实记录，不该被一次追溯改名改掉。这正是"快照不回溯"这条口径的又一次体现。
-- ============================================================================

update rate_rule set name = '周末上浮' where id = 1 and name = '周末钟点上浮';
