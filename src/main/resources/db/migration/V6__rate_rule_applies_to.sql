-- V6__rate_rule_applies_to.sql
--
-- 外部审阅指出的一条真实设计缺陷：一条 OVERRIDE 488 会<b>同时</b>改写"起步房费"和
-- "超时小时价"。于是"平时全日 388、超时 40/小时、假日一口价 488"这张单，
-- 延迟退房 1 小时会收出 488 + 488 = 976，而任何前台看到"假日房费 488"都会以为 528。
--
-- 根因不是算术错，是规则没声明自己改的是哪一笔钱。房费是打包价、超时是元/小时，
-- 同一个数值套到两种量纲上必然出意外。所以补一列把话说清楚：
--   ALL     —— 两笔都改（周末上浮这种"整体贵一点"的语义）
--   BASE    —— 只改房费/起步价（节假日一口价）
--   OVERAGE —— 只改超时单价（夜间超时加收）
-- 默认 ALL，保持已有行为不变；演示数据里那条"国庆全日房一口价"改成 BASE，
-- 因为它的名字里写的就是"房费"。
-- ============================================================================

alter table rate_rule
  add column applies_to varchar(8) not null default 'ALL'
    comment 'ALL=房费与超时单价都改；BASE=只改起步价；OVERAGE=只改超时单价'
    after value;

update rate_rule set applies_to = 'BASE' where id = 2;
